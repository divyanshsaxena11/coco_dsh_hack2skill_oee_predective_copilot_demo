SELECT COUNT(*) AS total_tests,
       COUNT_IF(PASSED) AS passed,
       COUNT_IF(NOT PASSED) AS failed,
       CASE WHEN COUNT_IF(NOT PASSED) = 0 THEN 'ALL GREEN' ELSE 'FAILURES DETECTED' END AS verdict
FROM _TEST_RESULTS;
